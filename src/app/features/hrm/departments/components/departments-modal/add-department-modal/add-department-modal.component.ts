import { Component, EventEmitter, Input, Output } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { MatSelectModule } from '@angular/material/select';
import { department } from '../../../../../../shared/models/models';
import { ModalFooterComponent } from '../../../../../common/modal-footer/modal-footer.component';
import { ModalHeaderComponent } from '../../../../../common/modal-header/modal-header.component';

@Component({
  selector: 'app-add-department-modal',
  standalone: true,
  imports: [
    CommonModule,
    FormsModule,
    MatSelectModule,
    ModalFooterComponent,
    ModalHeaderComponent,
  ],
  templateUrl: './add-department-modal.component.html',
})
export class AddDepartmentModalComponent {
  @Output() add = new EventEmitter<department>();
  @Output() cancel = new EventEmitter<void>();
@Input() open = false;

  onCancel() {
    this.cancel.emit();
  }

  model: department = {
    Department: '',
    NoOfEmployees: 0,
    Status: 'Actif',
    isSelected: false,
    id: Date.now(),// TODO: ID should be generated by backend

  };

 submit() {
  this.add.emit(this.model);
  this.onCancel(); // ferme le modal

  this.model = {
    id: Date.now(),
    Department: '',
    NoOfEmployees: 0,
    Status: 'Actif',
    isSelected: false,
  };
}

}
